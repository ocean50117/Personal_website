  var root=document.documentElement, ATTRS=['alt','title','aria-label','placeholder','data-title','data-note','data-labels','data-org'];
  var lang='zh', textOrig=new WeakMap(), attrOrig=new WeakMap(), metaOrig=null;
  function get(){try{return localStorage.getItem('lang')}catch(e){return null}}
  function save(v){try{localStorage.setItem('lang',v)}catch(e){}}
  var q=(location.search.match(/[?&]lang=(en|zh)/)||[])[1];
  function tr(zh){return lang==='en'&&DICT.hasOwnProperty(zh)?DICT[zh]:zh}
  function walk(en){
    var w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT),n,list=[];
    while(n=w.nextNode()){var p=n.parentElement;if(!p||/^(SCRIPT|STYLE|NOSCRIPT)$/.test(p.tagName)||p.closest('.lang-toggle'))continue;list.push(n)}
    list.forEach(function(n){
      var o=textOrig.get(n);
      if(!o){var v=n.nodeValue,t=v.trim();if(!t||!DICT.hasOwnProperty(t))return;
        o={zh:t,lead:v.slice(0,v.indexOf(t)),trail:v.slice(v.indexOf(t)+t.length)};textOrig.set(n,o)}
      n.nodeValue=en?o.lead+DICT[o.zh]+o.trail:o.lead+o.zh+o.trail});
    document.querySelectorAll('*').forEach(function(e){
      var o=attrOrig.get(e);
      ATTRS.forEach(function(a){
        if(!e.hasAttribute(a))return; if(e.id==='themeToggle'&&a==='title')return;
        if(!o){o={};attrOrig.set(e,o)}
        if(!(a in o)){var v=e.getAttribute(a);if(!DICT.hasOwnProperty(v))return;o[a]=v}
        e.setAttribute(a,en?DICT[o[a]]:o[a])})});
  }
  function setLang(v,persist){
    lang=v==='en'?'en':'zh'; root.setAttribute('lang',lang==='en'?'en':'zh-Hant');
    walk(lang==='en');
    var m=document.querySelector('meta[name="description"]');
    if(m){ if(metaOrig===null)metaOrig=m.getAttribute('content'); m.setAttribute('content',lang==='en'?META_EN.desc:metaOrig) }
    document.querySelectorAll('.lang-toggle button').forEach(function(b){var on=b.dataset.l===lang;b.classList.toggle('on',on);b.setAttribute('aria-pressed',on)});
    var tt=document.getElementById('themeToggle');if(tt)tt.title=root.getAttribute('data-theme')==='dark'?(lang==='en'?'Switch to light':'切換為淺色'):(lang==='en'?'Switch to dark':'切換為深色');
    if(persist)save(lang);
    window.I18N.lang=lang;
    try{window.dispatchEvent(new Event('resize'));setTimeout(function(){window.dispatchEvent(new Event('resize'))},350)}catch(e){}
    document.dispatchEvent(new CustomEvent('langchange',{detail:lang}));
  }
  window.I18N={lang:'zh',t:tr,set:setLang};
  function mount(){
    if(document.querySelector('.lang-toggle'))return;
    var wrap=document.createElement('div');wrap.className='lang-toggle';wrap.setAttribute('role','group');wrap.setAttribute('aria-label','Language');
    wrap.innerHTML='<button type="button" data-l="zh" lang="zh-Hant" aria-label="中文">中文</button><button type="button" data-l="en" lang="en" aria-label="English">EN</button>';
    wrap.addEventListener('click',function(e){var b=e.target.closest('button');if(b)setLang(b.dataset.l,true)});
    var t=document.getElementById('themeToggle'),cta=document.querySelector('header .pill.coral,.nav .pill.coral');
    var ref=t||cta;if(!ref)return;ref.parentNode.insertBefore(wrap,ref);
    setLang(q||get()||'zh',!!q);
  }
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',mount);else mount();
